// Writes the native play scripts (tests/native/*.play) from the rules: each
// round is won with rules.js's constructive always-match strategy (the one
// genLevel proves every level with), replayed through the real UI —
// Learn's three lessons by finger on the named vehicle/queue targets at a
// DPR-3 phone, Journey stages 1–2 by keys on a desktop window. Run
// `npm run plays` after a rules or UI change.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const R = createRequire(import.meta.url)('../rules.js');
const COLORS = ['amber', 'blue', 'coral', 'green', 'violet'];

/** The always-match moves (vehicle, queue) to a win. */
export function plan(cfg) {
  let s = R.genLevel(cfg);
  const moves = [];
  while (s.status === 'active') {
    let mv = null;
    for (let qi = 0; qi < s.q.length && !mv; qi++) {
      if (!s.q[qi].length) continue;
      const vi = s.v.findIndex((v) => v.c === s.q[qi][0] && v.n > 0);
      if (vi >= 0) mv = { v: vi, q: qi, s };
    }
    if (!mv) throw new Error('no plan for ' + cfg.id);
    moves.push(mv);
    s = R.dispatch(s, mv.v, mv.q).state;
  }
  if (s.status !== 'won') throw new Error('plan lost ' + cfg.id);
  return { moves, final: s };
}

function touchRound(cfg, out) {
  for (const { v, q, s } of plan(cfg).moves) {
    out.push(`touch =Vehicle ${v + 1}: ${COLORS[s.v[v].c - 1]}, ${s.v[v].n} left`, 'frames 8', `touch Queue ${q + 1}:`, 'frames 30');
  }
}
function keyRound(cfg, out) {
  for (const { v, q, s } of plan(cfg).moves) {
    const vt = s.v.map((x, i) => (x.n > 0 ? i : -1)).filter((i) => i >= 0);
    const qt = s.q.map((l, i) => (l.length ? i : -1)).filter((i) => i >= 0);
    for (let k = 0; k < vt.indexOf(v); k++) out.push('key ArrowRight 1', 'frames 3');
    out.push('key Enter 1', 'frames 8');
    for (let k = 0; k < qt.indexOf(q); k++) out.push('key ArrowRight 1', 'frames 3');
    out.push('key Enter 1', 'frames 30');
  }
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) writeAll();
function writeAll() {
const learn = ['# Generated by tools/gen-plays.mjs: Learn, all three lessons won by finger on the named targets.', '# viewport 390x844@3',
  'until 600 Transit Tangle', 'frames 30', 'touch =Play', 'until 600 Lesson 1', 'frames 20', 'save tt-learn-phone'];
for (let l = 0; l < 3; l++) {
  touchRound(R.tutorialConfig(l), learn);
  learn.push('until 300 All passengers away!', 'frames 10');
  if (l === 0) learn.push('save tt-learn-results');
  if (l < 2) learn.push('touch =Next lesson', `until 600 Lesson ${l + 2}`, 'frames 20');
}
learn.push('expect Tutorial complete', 'touch =Menu', 'until 300 Daily Challenge', 'expect Journey: 0/40 stages · wins 3');
writeFileSync('tests/native/learn-phone.play', learn.join('\n') + '\n');

const journey = ['# Generated by tools/gen-plays.mjs: Journey stages 1 and 2 won by keys (arrows + Enter) on a desktop window.', '# viewport 1280x800@1',
  'until 600 Transit Tangle', 'frames 30', 'click =Journey', 'until 300 Journey — 40 stages', 'frames 10', 'click =Stage 1',
  'until 300 journey-0', 'frames 150', 'save tt-journey'];
for (let st = 0; st < 2; st++) {
  keyRound(R.journeyConfig(st), journey);
  const { final } = plan(R.journeyConfig(st));
  journey.push('until 300 All passengers away!', 'frames 10', `expect ${R.scoreComponents(final).total}`);
  if (st === 0) journey.push('save tt-journey-results', 'click =Next stage', 'until 300 journey-1', 'frames 150');
}
journey.push('expect Score kept in your local records.', 'click =Menu', 'until 300 Journey: 2/40 stages · wins 2');
writeFileSync('tests/native/journey-keys.play', journey.join('\n') + '\n');
console.log('wrote tests/native/learn-phone.play, journey-keys.play');
}
